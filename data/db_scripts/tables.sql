CREATE TABLE ATHLETES (
	ATHLETE_ID INT GENERATED ALWAYS AS IDENTITY,
	FULL_NAME VARCHAR(255) NOT NULL,
	SCHOOL VARCHAR(255) NOT NULL DEFAULT 'UNKNOWN',
	GENDER VARCHAR(7) NOT NULL,
	CONSTRAINT UNIQ_PERSON UNIQUE (FULL_NAME, SCHOOL),
	PRIMARY KEY (ATHLETE_ID)
);

CREATE TABLE PERFORMANCES (
	PERFORMANCE_ID INT GENERATED ALWAYS AS IDENTITY,
	ATHLETE_ID BIGINT NOT NULL,
	STUDENT_YEAR VARCHAR(255) NOT NULL,
	MEET_DATE DATE NOT NULL,
	EVENT_CLASS VARCHAR(255) NOT NULL,
	TIME VARCHAR(255) NOT NULL,
	WIND VARCHAR(255) NOT NULL DEFAULT 'UNKNOWN',
	CONFERENCE_RANK VARCHAR(7),
	CONSTRAINT FK_ATHLETE_ID FOREIGN KEY (ATHLETE_ID) REFERENCES ATHLETES (ATHLETE_ID),
	PRIMARY KEY (PERFORMANCE_ID)
);